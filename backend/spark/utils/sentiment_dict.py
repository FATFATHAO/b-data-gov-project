def dict_match(text: str, dict_pos: Dict[str, float], dict_neg: Dict[str, float]) -> float:
    """
    词典匹配情感分析

    Args:
        text: 待分析文本
        dict_pos: 正面词典
        dict_neg: 负面词典

    Returns:
        情感分数 (0.0-1.0)，-1 表示未匹配
        - 正面情感: 分数越高越正面
        - 负面情感: 分数越低越负面
        - 中性词或未命中: 返回 -1
    """
    if not text:
        return -1.0

    text = text.lower()
    pos_hits: List[Tuple[str, float]] = []
    neg_hits: List[Tuple[str, float]] = []

    # 匹配多词组合优先 (如 "太可爱了")
    for word, score in dict_pos.items():
        if word in text:
            pos_hits.append((word, score))

    for word, score in dict_neg.items():
        if word in text:
            neg_hits.append((word, score))

    if not pos_hits and not neg_hits:
        return -1.0

    # 按词长度降序排序，优先匹配更长的词组
    pos_hits.sort(key=lambda x: len(x[0]), reverse=True)
    neg_hits.sort(key=lambda x: len(x[0]), reverse=True)

    # 计算得分
    pos_score = max([s for _, s in pos_hits]) if pos_hits else 0.0
    neg_score = min([s for _, s in neg_hits]) if neg_hits else 1.0

    if pos_hits and not neg_hits:
        return pos_score
    elif neg_hits and not pos_hits:
        return neg_score
    else:
        # 双方都有命中
        if abs(pos_score - 0.5) > abs(neg_score - 0.5):
            return pos_score
        else:
            return neg_score


def snownlp_score(text: str) -> float:
    """
    使用 SnowNLP 进行情感分析 (兜底方案)

    Args:
        text: 待分析文本

    Returns:
        情感分数 (0.0-1.0)
        - score > 0.65: 返回 0.8 (偏好)
        - score < 0.35: 返回 0.2 (偏坏)
        - 0.35 ~ 0.65: 返回 -1.0 (中性，跳过)
    """
    try:
        from snownlp import SnowNLP

        s = SnowNLP(text)
        score = s.sentiments  # 0-1 范围

        if score > 0.65:
            return 0.8
        elif score < 0.35:
            return 0.2
        else:
            return -1.0  # 中性，跳过
    except Exception:
        return -1.0


def analyze_sentiment(text: str) -> float:
    """
    综合情感分析 (两层策略)

    第一层: 词典匹配 (精准快速)
    第二层: SnowNLP 兜底 (广度覆盖)

    Args:
        text: 待分析文本

    Returns:
        情感分数 (0.0-1.0)，-1 表示中性/无效
    """
    if not text or len(text.strip()) == 0:
        return -1.0

    # 预处理：去除特殊字符但保留中文和基本标点
    text_clean = re.sub(r'[^\u4e00-\u9fa5a-zA-Z0-9\s。！？，、]', '', text)

    # 第一层：词典匹配
    score = dict_match(text_clean, DICT_POS, DICT_NEG)
    if score >= 0:
        return score

    # 第二层：SnowNLP 兜底
    return snownlp_score(text_clean)


def batch_analyze(texts: list) -> list:
    """
    批量情感分析

    Args:
        texts: 文本列表

    Returns:
        情感分数列表
    """
    return [analyze_sentiment(t) for t in texts]
