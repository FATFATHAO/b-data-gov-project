# 合并所有停用词
STOP_WORDS: FrozenSet[str] = STOP_WORDS_BASE | STOP_WORDS_EXTENDED


def is_stopword(word: str) -> bool:
    """
    判断词是否为停用词

    Args:
        word: 待检测的词

    Returns:
        True 如果是停用词，否则 False
    """
    return word in STOP_WORDS


def filter_stopwords(words: list) -> list:
    """
    过滤停用词

    Args:
        words: 词列表

    Returns:
        过滤后的词列表
    """
    return [w for w in words if w and not is_stopword(w) and len(w) > 1]
